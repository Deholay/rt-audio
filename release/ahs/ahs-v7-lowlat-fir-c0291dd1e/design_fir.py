"""Design + verify the 48<->16 kHz FIR pair for ahs-v7-lowlat-fir, against the
AHS resampler R2 criteria (docs/windows_a_resampler_revision2_for_review.md @ c0291dd1e):
  passband 0-6500 Hz both directions, |dev| <= 0.10 dB
  down stopband 8000-24000 Hz >= 70 dB;  up stopband 8200-24000 Hz >= 70 dB
  cascade 48->16->48 (identity middle) images 8000-24000 Hz >= 70 dB rel. input
  per-direction delay <= 2.1 ms
Linear-phase equiripple (Parks-McClellan), odd length -> integer group delay.
Writes fir_coeffs.hpp (float). Verification uses the float coefficients.
Usage: python design_fir.py [--write]"""
import sys
from pathlib import Path

import numpy as np
from scipy.signal import remez, freqz

FS = 48000
NFFT = 1 << 19  # grid >= 262144


def design(stop_hz, taps, w_stop):
    return remez(taps, [0, 6500, stop_hz, FS / 2], [1, 0], weight=[1, w_stop], fs=FS)


def resp_db(h, gain=1.0):
    w, H = freqz(h * gain, worN=NFFT, fs=FS)
    return w, 20 * np.log10(np.abs(H) + 1e-300)


def check(h_down, h_up):
    """h_down: decimator taps (DC gain 1). h_up: interpolator taps (DC gain 3)."""
    r = {}
    w, d = resp_db(h_down)
    _, u = resp_db(h_up, 1 / 3)
    pb = w <= 6500
    r["down_passband_dev_db"] = float(np.max(np.abs(d[pb] - d[0])))
    r["up_passband_dev_db"] = float(np.max(np.abs(u[pb] - u[0])))
    r["down_stop_db"] = float(-np.max(d[w >= 8000]))
    r["up_stop_db"] = float(-np.max(u[w >= 8200]))
    r["up_8000_db"] = float(-u[np.argmin(np.abs(w - 8000))])
    r["up_8100_db"] = float(-u[np.argmin(np.abs(w - 8100))])
    # cascade images: input fin -> folds to f0 in [0,8000] at 16 kHz -> images k*16000+-f0.
    # amplitude = |Hd(fin)| * |Hu(fimage)| (identity middle), worst over fin grid (1 Hz).
    Hd = lambda f: np.abs(np.interp(f, w, 10 ** (d / 20)))
    Hu = lambda f: np.abs(np.interp(f, w, 10 ** (u / 20)))
    fin = np.arange(0, 24001, 1.0)
    f0 = np.abs(((fin + 8000) % 16000) - 8000)
    worst = -np.inf
    for k in range(0, 2):
        for s in (+1, -1):
            fim = np.abs(k * 16000 + s * f0)
            m = (fim >= 8000) & (fim <= 24000) & (np.abs(fim - fin) > 0.5)
            if m.any():
                worst = max(worst, float(np.max(20 * np.log10(Hd(fin[m]) * Hu(fim[m]) + 1e-300))))
    r["cascade_image_db"] = -worst
    r["dc_down"] = float(abs(np.sum(h_down) - 1))
    r["dc_up"] = float(abs(np.sum(h_up) / 3 - 1))
    r["down_delay_ms"] = (len(h_down) - 1) / 2 / FS * 1e3
    r["up_delay_ms"] = (len(h_up) - 1) / 2 / FS * 1e3
    return r


def passes(r):
    return (r["down_passband_dev_db"] <= 0.10 and r["up_passband_dev_db"] <= 0.10
            and r["down_stop_db"] >= 70 and r["up_stop_db"] >= 70 and r["cascade_image_db"] >= 70
            and r["dc_down"] <= 1e-4 and r["dc_up"] <= 1e-4
            and r["down_delay_ms"] <= 2.1 and r["up_delay_ms"] <= 2.1)


def shortest(stop_hz, margin_db=3.0):
    """Shortest odd length meeting passband <=0.10 dB and stopband >= 70+margin dB."""
    for taps in range(41, 401, 2):
        for w_stop in (1, 3, 10, 30, 100):
            h = design(stop_hz, taps, w_stop)
            h = h / np.sum(h)
            w, d = resp_db(h)
            pb = np.max(np.abs(d[w <= 6500] - d[0]))
            sb = -np.max(d[w >= stop_hz])
            if pb <= 0.08 and sb >= 70 + margin_db:
                return h.astype(np.float32).astype(np.float64), taps, w_stop
    raise RuntimeError("no design")


if __name__ == "__main__":
    hd, nd, wd = shortest(8000)
    hu, nu, wu = shortest(8200)
    hu = 3 * hu
    hu = (hu.astype(np.float32)).astype(np.float64)
    r = check(hd, hu)
    print(f"down: {nd} taps (w_stop {wd}), up: {nu} taps (w_stop {wu})")
    for k, v in r.items():
        print(f"  {k:<22} {v:.6g}")
    print("R2 PASS" if passes(r) else "R2 FAIL")
    if "--write" in sys.argv:
        fmt = lambda h: ",\n    ".join(", ".join(f"{x:.9e}F" for x in h[i:i + 4]) for i in range(0, len(h), 4))
        Path(__file__).with_name("fir_coeffs.hpp").write_text(
            "// Generated by design_fir.py. Linear-phase equiripple FIR, 48 kHz.\n"
            "// Verified against AHS resampler R2 criteria (see design_fir.py output).\n#pragma once\n#include <array>\n\n"
            "namespace rt_audio::ahs::v7_lowlat_fir_c0291dd1e {\n\n"
            f"// 48 -> 16 kHz decimator, DC gain 1, {nd} taps, delay {(nd - 1) // 2} samples @48 kHz.\n"
            f"inline constexpr std::array<float, {nd}> down_taps{{\n    {fmt(hd)}}};\n\n"
            f"// 16 -> 48 kHz interpolator (zero-stuffed), DC gain 3, {nu} taps, delay {(nu - 1) // 2} samples @48 kHz.\n"
            f"inline constexpr std::array<float, {nu}> up_taps{{\n    {fmt(hu)}}};\n\n"
            "} // namespace rt_audio::ahs::v7_lowlat_fir_c0291dd1e\n")
        print("wrote fir_coeffs.hpp")
